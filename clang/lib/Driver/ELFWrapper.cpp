// ============================================================================
// 生成 loader.S 壳入口跳板
// ============================================================================

static bool generateLoaderAsm(const std::string &output_path,
                              StringRef TargetTriple) {
  std::error_code EC;
  raw_fd_ostream OS(output_path, EC, sys::fs::OF_None);
  if (EC) {
    errs() << "Error: Cannot write loader.S: " << EC.message() << "\n";
    return false;
  }

  if (TargetTriple.starts_with("aarch64")) {
    OS << R"(.text
.globl _start
.type _start, %function
.extern irobf_loader_entry
_start:
    mov x29, xzr
    mov x30, xzr
    ldr x0, [sp]
    add x1, sp, #8
    add x2, x1, x0, lsl #3
    add x2, x2, #8
    bl irobf_loader_entry
    mov x8, #93
    svc #0
    b .
.size _start, . - _start
.section .note.GNU-stack,"",%progbits
)";
  } else {
    errs() << "Error: [irobf-linker] loader.S trampoline only supports aarch64 currently\n";
    return false;
  }

  OS.flush();
  return true;
}

// ============================================================================
// 执行 ELF 加壳
// ============================================================================

bool clang::driver::performELFWrapping(const std::string &InputELF,
                                const std::string &OutputPath,
                                const std::string &TargetTriple,
                                const std::string &ClangPath,
                                const std::string &Sysroot,
                                bool DebugMode) {
  // 1. 读取原始 ELF 文件
  std::ifstream in(InputELF, std::ios::binary | std::ios::ate);
  if (!in.is_open()) {
    errs() << "Error: [irobf-linker] Cannot open input ELF: " << InputELF << "\n";
    return false;
  }
  size_t file_size = in.tellg();
  in.seekg(0, std::ios::beg);

  std::vector<uint8_t> elf_data(file_size);
  if (!in.read(reinterpret_cast<char *>(elf_data.data()), file_size)) {
    errs() << "Error: [irobf-linker] Cannot read input ELF\n";
    return false;
  }
  in.close();

  // 验证 ELF 魔数
  if (elf_data.size() < 4 || elf_data[0] != 0x7f || elf_data[1] != 'E' ||
      elf_data[2] != 'L' || elf_data[3] != 'F') {
    errs() << "Warning: [irobf-linker] Input is not a valid ELF, skipping wrapper\n";
    // 不是 ELF，直接复制原文件
    sys::fs::copy_file(InputELF, OutputPath);
    return true;
  }

  if (DebugMode) outs() << "[irobf-linker] Wrapping ELF: " << file_size << " bytes\n";

  // 获取 clang 所在目录
  SmallString<128> clangDir;
  {
    SmallString<128> absClangPath(ClangPath);
    sys::fs::make_absolute(absClangPath);
    clangDir = sys::path::parent_path(absClangPath);
  }

  // 使用 llvm-strip 剥离符号表
  SmallString<256> llvmStripPath;
  sys::path::append(llvmStripPath, clangDir, "llvm-strip");
#ifdef _WIN32
  sys::path::replace_extension(llvmStripPath, "exe");
#endif
  if (sys::fs::exists(llvmStripPath)) {
    // 创建临时文件用于存储剥离符号后的 ELF
    SmallString<256> strippedPath(clangDir);
    std::string strippedName = (Twine(".linker_stripped_") +
                                Twine(sys::Process::getProcessId()) + "_" +
                                Twine(sys::path::filename(OutputPath)))
                                   .str();
    sys::path::append(strippedPath, strippedName);
    
    SmallVector<StringRef, 8> stripArgs;
    stripArgs.push_back(llvmStripPath);
    stripArgs.push_back("--strip-unneeded");
    stripArgs.push_back("-o");
    stripArgs.push_back(strippedPath);
    stripArgs.push_back(InputELF);
    
    std::string stripErrMsg;
    int stripRet = sys::ExecuteAndWait(llvmStripPath, stripArgs, {}, {}, 0, 0, &stripErrMsg);
    if (stripRet == 0) {
      // 重新读取剥离符号后的文件
      std::ifstream strippedFile(std::string(strippedPath.str()));
      if (strippedFile.is_open()) {
        strippedFile.seekg(0, std::ios::end);
        file_size = strippedFile.tellg();
        strippedFile.seekg(0, std::ios::beg);
        elf_data.resize(file_size);
        strippedFile.read(reinterpret_cast<char *>(elf_data.data()), file_size);
        strippedFile.close();
        if (DebugMode) outs() << "[irobf-linker] Stripped symbols, new size: " << file_size << " bytes\n";
      }
      sys::fs::remove(strippedPath);
    } else {
      if (DebugMode) outs() << "[irobf-linker] Warning: llvm-strip failed, using original ELF\n";
    }
  }

  // 2. 生成随机密钥并加密
  uint8_t key[32], nonce[12];
  generate_random_key(key, nonce);

  // 从 clang 同目录的 .linker_env_key[.<tag>] 文件读取密钥（由 EnvCheck Pass 生成）
  SmallString<256> linkerKeyPath;
  std::string linkerKeyFileName = ".linker_env_key";
  if (auto keyTag = sys::Process::GetEnv("IROBF_KEY_TAG"))
    linkerKeyFileName += "." + *keyTag;
  sys::path::append(linkerKeyPath, clangDir, linkerKeyFileName);
  std::string linkerKeyPathStr = std::string(linkerKeyPath.str());
  std::string env_key(32, '\0');
  {
    std::ifstream keyFile(linkerKeyPathStr);
    if (keyFile.is_open()) {
      keyFile.read(&env_key[0], 32);
      keyFile.close();
      if (DebugMode) outs() << "[irobf-linker] Read key from " << linkerKeyPath << ": " << env_key << "\n";
    } else {
      // 如果文件不存在，生成随机密钥
      if (DebugMode) outs() << "[irobf-linker] Warning: " << linkerKeyPath << " not found, generating random key\n";
      std::random_device rd;
      std::mt19937 gen(rd());
      std::uniform_int_distribution<int> dist(0, 15);
      const char hex[] = "0123456789abcdef";
      for (int i = 0; i < 32; i++)
        env_key[i] = hex[dist(gen)];
    }
  }

  std::vector<uint8_t> encrypted_data(file_size);
  chacha20_encrypt(elf_data.data(), file_size, key, nonce, encrypted_data.data());

  // 3. 创建临时目录
  SmallString<128> tmp_dir;
  std::error_code EC = sys::fs::createUniqueDirectory("elf-wrapper", tmp_dir);
  if (EC) {
    errs() << "Error: [irobf-linker] Cannot create temp directory: " << EC.message() << "\n";
    return false;
  }

  std::string payload_h_path = (tmp_dir + "/payload.h").str();
  std::string loader_cpp_path = (tmp_dir + "/loader.cpp").str();
  std::string loader_asm_path = (tmp_dir + "/loader.S").str();
  std::string wrapped_elf_path = (tmp_dir + "/wrapped.elf").str();
  bool useAsmTrampoline = StringRef(TargetTriple).starts_with("aarch64");

  // 4. 生成 payload.h / loader.cpp / loader.S
  if (!generatePayloadH(payload_h_path, encrypted_data.data(), file_size, key, nonce, env_key)) {
    sys::fs::remove_directories(tmp_dir);
    return false;
  }

  if (!generateLoaderCpp(loader_cpp_path, DebugMode, useAsmTrampoline)) {
    sys::fs::remove_directories(tmp_dir);
    return false;
  }

  if (useAsmTrampoline &&
      !generateLoaderAsm(loader_asm_path, TargetTriple)) {
    sys::fs::remove_directories(tmp_dir);
    return false;
  }

  // 规范化路径（去掉 .. 等，统一使用绝对路径）
  std::string normalized_clang, normalized_sysroot;
  SmallString<128> abs_path(ClangPath);
  sys::fs::make_absolute(abs_path);
  sys::path::remove_dots(abs_path, /*remove_dot_dot=*/true);
  normalized_clang = std::string(abs_path);

  if (!Sysroot.empty()) {
    abs_path = Sysroot;
    sys::fs::make_absolute(abs_path);
    sys::path::remove_dots(abs_path, /*remove_dot_dot=*/true);
    normalized_sysroot = std::string(abs_path);
  }

  // 5. 编译壳程序 - 调用 clang 自身，最高强度混淆
  std::string compile_cmd =
      "\"" + normalized_clang + "\""
      + " -target " + TargetTriple;
  if (!normalized_sysroot.empty())
    compile_cmd += " --sysroot=\"" + normalized_sysroot + "\"";
  compile_cmd += std::string(" -O2 -std=c++17 -fno-exceptions -frtti -fPIE -pie");
  if (useAsmTrampoline)
    compile_cmd += " -nostartfiles -Wl,-e,_start";
  // 混淆编译参数已注释关闭（保持仅基础编译参数）
  // compile_cmd += " -mllvm -irobf";
  // compile_cmd += " -mllvm -irobf-indbr -mllvm -level-indbr=3";
  // compile_cmd += " -mllvm -irobf-icall -mllvm -level-icall=3";
  // compile_cmd += " -mllvm -irobf-fla";
  // compile_cmd += " -mllvm -irobf-indgv -mllvm -level-indgv=3";
  // compile_cmd += " -mllvm -irobf-cse";
  // compile_cmd += " -mllvm -irobf-cie -mllvm -level-cie=3";
  // compile_cmd += " -mllvm -irobf-cfe -mllvm -level-cfe=3";
  // compile_cmd += " -mllvm -irobf-rtti";
  // compile_cmd += " -mllvm -irobf-syscall";
  compile_cmd += " -lm -ldl -llog";
  compile_cmd += " -o \"" + wrapped_elf_path + "\"";
  compile_cmd += " \"" + loader_cpp_path + "\"";
  if (useAsmTrampoline)
    compile_cmd += " \"" + loader_asm_path + "\"";
  compile_cmd += " -I\"" + std::string(tmp_dir.str()) + "\"";

  if (DebugMode) outs() << "[irobf-linker] Compiling wrapper with max obfuscation...\n";

  // 使用 llvm::sys::ExecuteAndWait 替代 system()，避免 Windows cmd.exe 路径问题
  SmallVector<StringRef, 64> argv;
  argv.push_back(normalized_clang);
  argv.push_back("-target");
  argv.push_back(TargetTriple);
  if (!normalized_sysroot.empty()) {
    argv.push_back("--sysroot");
    argv.push_back(normalized_sysroot);
  }
  argv.push_back("-O2");
  argv.push_back("-std=c++17");
  argv.push_back("-fno-exceptions");
  argv.push_back("-frtti");
  argv.push_back("-fPIE");
  argv.push_back("-pie");
  if (useAsmTrampoline) {
    argv.push_back("-nostartfiles");
    argv.push_back("-Wl,-e,_start");
  }
  // 混淆编译参数已注释关闭（保持仅基础编译参数）
  // argv.push_back("-mllvm"); argv.push_back("-irobf");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-indbr");
  // argv.push_back("-mllvm"); argv.push_back("-level-indbr=3");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-icall");
  // argv.push_back("-mllvm"); argv.push_back("-level-icall=3");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-fla");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-indgv");
  // argv.push_back("-mllvm"); argv.push_back("-level-indgv=3");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-cse");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-cie");
  // argv.push_back("-mllvm"); argv.push_back("-level-cie=3");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-cfe");
  // argv.push_back("-mllvm"); argv.push_back("-level-cfe=3");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-rtti");
  // argv.push_back("-mllvm"); argv.push_back("-irobf-syscall");
  argv.push_back("-lm");
  argv.push_back("-ldl");
  argv.push_back("-llog");
  argv.push_back("-o");
  argv.push_back(wrapped_elf_path);
  argv.push_back(loader_cpp_path);
  if (useAsmTrampoline)
    argv.push_back(loader_asm_path);
  std::string include_arg = "-I" + std::string(tmp_dir.str());
  argv.push_back(include_arg);

  std::string errMsg;
  int ret = sys::ExecuteAndWait(normalized_clang, argv, {},
                                 {}, 0, 0, &errMsg);

  if (ret != 0) {
    errs() << "Error: [irobf-linker] Wrapper compilation failed (code: " << ret << ")";
    if (!errMsg.empty()) errs() << ": " << errMsg;
    errs() << "\n";
    sys::fs::remove_directories(tmp_dir);
    return false;
  }

  // 6. 复制到输出路径
  EC = sys::fs::copy_file(wrapped_elf_path, OutputPath);
  if (EC) {
    errs() << "Error: [irobf-linker] Cannot copy to output: " << EC.message() << "\n";
    sys::fs::remove_directories(tmp_dir);
    return false;
  }

  // 设置可执行权限
  sys::fs::setPermissions(OutputPath, sys::fs::perms::all_read |
                                          sys::fs::perms::all_write |
                                          sys::fs::perms::owner_exe |
                                          sys::fs::perms::group_exe |
                                          sys::fs::perms::others_exe);

  // 清理临时文件
  sys::fs::remove_directories(tmp_dir);
  // 删除链接器输出的临时文件
  sys::fs::remove(InputELF);
  // 删除密钥文件
  sys::fs::remove(linkerKeyPath);

  if (DebugMode) outs() << "[irobf-linker] Done! Wrapped ELF: " << OutputPath << "\n";
  return true;
}

// ============================================================================
// Base64 编码
// ============================================================================

static const char base64_table[] =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

static std::string base64_encode(const uint8_t *data, size_t len) {
  std::string result;
  result.reserve((len + 2) / 3 * 4);
  for (size_t i = 0; i < len; i += 3) {
    uint32_t n = (uint32_t)data[i] << 16;
    if (i + 1 < len) n |= (uint32_t)data[i + 1] << 8;
    if (i + 2 < len) n |= (uint32_t)data[i + 2];
    result.push_back(base64_table[(n >> 18) & 0x3F]);
    result.push_back(base64_table[(n >> 12) & 0x3F]);
    result.push_back((i + 1 < len) ? base64_table[(n >> 6) & 0x3F] : '=');
    result.push_back((i + 2 < len) ? base64_table[n & 0x3F] : '=');
  }
  return result;
}

// ============================================================================
// gzip 压缩（使用 LLVM 内置 zlib 支持）
// ============================================================================

static bool gzip_compress(const uint8_t *input, size_t input_len,
                          std::vector<uint8_t> &output) {
  if (!compression::zlib::isAvailable()) {
    errs() << "Error: [irobf-gz] zlib not available in this build\n";
    return false;
  }
  SmallVector<uint8_t, 0> compressed;
  compression::zlib::compress(ArrayRef<uint8_t>(input, input_len),
                              compressed,
                              compression::zlib::BestSizeCompression);
  output.assign(compressed.begin(), compressed.end());
  return true;
}

// ============================================================================
// 执行 gzip+base64 压缩壳（生成 shell 脚本）
// ============================================================================

bool clang::driver::performGzWrapping(const std::string &InputELF,
                                      const std::string &OutputPath,
                                      const std::string &TargetTriple,
                                      const std::string &ClangPath,
                                      const std::string &Sysroot,
                                      bool DebugMode) {
  // 1. 读取输入 ELF 文件
  std::ifstream in(InputELF, std::ios::binary | std::ios::ate);
  if (!in.is_open()) {
    errs() << "Error: [irobf-gz] Cannot open input ELF: " << InputELF << "\n";
    return false;
  }
  size_t file_size = in.tellg();
  in.seekg(0, std::ios::beg);

  std::vector<uint8_t> elf_data(file_size);
  if (!in.read(reinterpret_cast<char *>(elf_data.data()), file_size)) {
    errs() << "Error: [irobf-gz] Cannot read input ELF\n";
    return false;
  }
  in.close();

  // 验证 ELF 魔数
  if (elf_data.size() < 4 || elf_data[0] != 0x7f || elf_data[1] != 'E' ||
      elf_data[2] != 'L' || elf_data[3] != 'F') {
    errs() << "Warning: [irobf-gz] Input is not a valid ELF, skipping wrapper\n";
    sys::fs::copy_file(InputELF, OutputPath);
    return true;
  }

  if (DebugMode) outs() << "[irobf-gz] Compressing ELF: " << file_size << " bytes\n";

  // 获取 clang 所在目录
  SmallString<128> clangDir;
  {
    SmallString<128> absClangPath(ClangPath);
    sys::fs::make_absolute(absClangPath);
    clangDir = sys::path::parent_path(absClangPath);
  }

  // 使用 llvm-strip 剥离符号表
  SmallString<256> llvmStripPath;
  sys::path::append(llvmStripPath, clangDir, "llvm-strip");
#ifdef _WIN32
  sys::path::replace_extension(llvmStripPath, "exe");
#endif
  if (sys::fs::exists(llvmStripPath)) {
    // 创建临时文件用于存储剥离符号后的 ELF
    SmallString<256> strippedPath;
    sys::path::append(strippedPath, clangDir, ".gz_stripped");
    
    SmallVector<StringRef, 8> stripArgs;
    stripArgs.push_back(llvmStripPath);
    stripArgs.push_back("--strip-unneeded");
    stripArgs.push_back("-o");
    stripArgs.push_back(strippedPath);
    stripArgs.push_back(InputELF);
    
    std::string stripErrMsg;
    int stripRet = sys::ExecuteAndWait(llvmStripPath, stripArgs, {}, {}, 0, 0, &stripErrMsg);
    if (stripRet == 0) {
      // 重新读取剥离符号后的文件
      std::ifstream strippedFile(std::string(strippedPath.str()));
      if (strippedFile.is_open()) {
        strippedFile.seekg(0, std::ios::end);
        file_size = strippedFile.tellg();
        strippedFile.seekg(0, std::ios::beg);
        elf_data.resize(file_size);
        strippedFile.read(reinterpret_cast<char *>(elf_data.data()), file_size);
        strippedFile.close();
        if (DebugMode) outs() << "[irobf-gz] Stripped symbols, new size: " << file_size << " bytes\n";
      }
      sys::fs::remove(strippedPath);
    } else {
      if (DebugMode) outs() << "[irobf-gz] Warning: llvm-strip failed, using original ELF\n";
    }
  }

  // 从 clang 同目录的 .gz_env_key[.<tag>] 文件读取密钥（由 GzEnvCheck Pass 生成）
  SmallString<256> gzKeyPath;
  std::string gzKeyFileName = ".gz_env_key";
  if (auto keyTag = sys::Process::GetEnv("IROBF_KEY_TAG"))
    gzKeyFileName += "." + *keyTag;
  sys::path::append(gzKeyPath, clangDir, gzKeyFileName);
  std::string gzKeyPathStr = std::string(gzKeyPath.str());
  std::string gz_env_key(32, '\0');
  {
    std::ifstream keyFile(gzKeyPathStr);
    if (keyFile.is_open()) {
      keyFile.read(&gz_env_key[0], 32);
      keyFile.close();
      if (DebugMode) outs() << "[irobf-gz] Read key from " << gzKeyPath << ": " << gz_env_key << "\n";
    } else {
      // 如果文件不存在，生成随机密钥
      if (DebugMode) outs() << "[irobf-gz] Warning: " << gzKeyPath << " not found, generating random key\n";
      std::random_device rd;
      std::mt19937 gen(rd());
      std::uniform_int_distribution<int> dist(0, 15);
      const char hex[] = "0123456789abcdef";
      for (int i = 0; i < 32; i++)
        gz_env_key[i] = hex[dist(gen)];
    }
  }

  // 3. base64 编码（跳过 gzip 压缩，直接编码原始 ELF）
  std::string b64_data = base64_encode(elf_data.data(), file_size);
  if (DebugMode) outs() << "[irobf-gz] Base64 encoded: " << b64_data.size() << " bytes\n";

  size_t hidden_pos = b64_data.size() / 2;
  std::string b64_prefix = b64_data.substr(0, hidden_pos);
  std::string b64_suffix = b64_data.substr(hidden_pos);

  // 4. 生成 shell 脚本
  std::error_code EC;
  raw_fd_ostream OS(OutputPath, EC, sys::fs::OF_None);
  if (EC) {
    errs() << "Error: [irobf-gz] Cannot write output: " << EC.message() << "\n";
    return false;
  }

  // Shell 脚本头部
  OS << "#!/system/bin/sh\n";
  OS << "# By.abcdefgjh 给小辈一个面子，别破解了，相信大牛你的实力了\n";
  constexpr size_t kShellChunkSize = 512;
  auto emitShellAppend = [&](const std::string &Data) {
    for (size_t I = 0; I < Data.size(); I += kShellChunkSize) {
      OS << "echo -n '" << Data.substr(I, kShellChunkSize) << "'>>\"$F\";";
    }
  };

  OS << "T=/data/local/tmp/.gz_$$;F=\"$T.b64\";trap 'rm -f \"$T\" \"$F\"' EXIT;:>\"$F\";";
  emitShellAppend(b64_prefix);
  OS << "K='" << gz_env_key << "';export lc_gz=\"$K\";unset K;";
  emitShellAppend(b64_suffix);
  OS << "base64 -d<\"$F\">\"$T\" 2>/dev/null;chmod 700 \"$T\";"
        "\"$T\" \"$@\";R=$?;rm -f \"$T\" \"$F\";exit $R\n";

  OS.flush();

  // 设置可执行权限
  sys::fs::setPermissions(OutputPath, sys::fs::perms::all_read |
                                          sys::fs::perms::all_write |
                                          sys::fs::perms::owner_exe |
                                          sys::fs::perms::group_exe |
                                          sys::fs::perms::others_exe);

  // 删除输入文件
  sys::fs::remove(InputELF);
  // 删除密钥文件
  sys::fs::remove(gzKeyPath);

  if (DebugMode) outs() << "[irobf-gz] Done! Shell wrapper: " << OutputPath << "\n";
  return true;
}
